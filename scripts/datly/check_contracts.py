#!/usr/bin/env python3
"""Enforce the versionless native persistence and generated ownership boundary."""
import re
from pathlib import Path
from contracts import PROJECT_ROOT, contract_inventory, generated_files
from sql_aliases import alias_errors
project = PROJECT_ROOT
module, inventory = contract_inventory(project)
prohibited = [r'"github.com/viant/datly/(repository|view|service)(?:/|\")', r'\.Stater\(', r'\.Db\(', r'\.(?:ExecContext|QueryContext|QueryRowContext)\(', r'\.AddHandler\(', r'\bRegisterType\(']
errors=[]
for file in sorted(set((project/'internal/store').rglob('*.go')) | set((project/'internal/datly').rglob('*.go'))):
    relative=file.relative_to(project)
    if 'contracttest' in relative.parts or file.name.endswith('_test.go'):
        continue
    text=file.read_text()
    for pattern in prohibited:
        if re.search(pattern,text):errors.append(str(relative)+': '+pattern)
    if '"database/sql"' in text:
        errors.append(str(relative)+': product SQL handle')
for item in inventory:
    file = project / item['new_dql']
    for line, alias in alias_errors(file.read_text()):
        errors.append(f'{file.relative_to(project)}:{line}: unquoted MySQL reserved table/view alias {alias!r}')
    package = re.search(r"#package\(['\"]([^'\"]+)['\"]\)",file.read_text())
    if not package or package[1] != item['new_package']:
        errors.append(str(file.relative_to(project))+': missing or mismatched canonical package')
# Native Datly now overwrites generated artifacts without package sidecars.
# The Endly regeneration step verifies all bytes against the DQL; this check
# restricts authored Go to the explicitly permitted business hook filenames.
generated_roles = {
    'actions.go','entities.go','frames.go','indexes.go','input.go',
    'client_input.go','client_input_setters.go',
    'input_setters.go','layout.go','links.go','mutation.go','mutation_output.go',
    'output.go','output_setters.go','previous.go','resources.go','router.go',
    'validation.go','views.go',
}
for path in generated_files(project):
    if path.suffix == '.sql':
        for line, alias in alias_errors(path.read_text()):
            errors.append(f'{path.relative_to(project)}:{line}: emitted unquoted MySQL reserved table/view alias {alias!r}')
    if path.suffix != '.go':
        continue
    if path.name not in {'lifecycle.go','hooks.go'} and not path.read_text().startswith('// Code generated by Datly'):
        errors.append(str(path.relative_to(project))+': missing native generator header')
    if path.name not in generated_roles | {'lifecycle.go','hooks.go'}:
        errors.append(str(path.relative_to(project))+': unexpected authored contract/plumbing')
if errors:raise SystemExit('\n'.join(errors))
print('Native boundary passed: native artifact roles and business hooks only; no legacy APIs or direct product SQL; byte ownership checked separately by regeneration')
