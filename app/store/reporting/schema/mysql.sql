  CONSTRAINT `chk_report_export_job_run_reference` CHECK ((((`report_run_id` is null) and (`report_run_revision` is null) and (`export_request_id` is null)) or ((`report_run_id` is not null) and (`report_run_revision` is not null) and (`report_run_revision` > 0) and (`export_request_id` is not null) and (`conversation_id` is not null)))),
  CONSTRAINT `chk_report_export_job_run_pdf` CHECK (((`report_run_id` is null) or ((`format` = _utf8mb4'pdf') and (`scope` = _utf8mb4'draft'))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

