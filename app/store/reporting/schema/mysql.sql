  `diagnostics_json` mediumblob,
  `submitted_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `started_at` datetime DEFAULT NULL,
  `completed_at` datetime DEFAULT NULL,
  `retention_ttl_sec` bigint NOT NULL DEFAULT '0',
  `report_run_id` varchar(255) DEFAULT NULL,
  `report_run_revision` bigint DEFAULT NULL,
  `export_request_id` varchar(128) DEFAULT NULL,
  PRIMARY KEY (`job_id`),
  UNIQUE KEY `ux_report_export_job_owner_conversation_request` (`owner_id`,`conversation_id`,`export_request_id`),
  KEY `idx_report_export_job_owner_submitted_at` (`owner_id`,`submitted_at`),
